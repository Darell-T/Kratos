//! A typed client for `codex app-server`, the JSON-RPC server inside the Codex CLI.
//!
//! [`connect`] starts the server inside a [`kratos_process::OwnedChild`], performs the handshake,
//! and returns a [`Codex`] handle for requests plus a stream of [`Incoming`] messages:
//! notifications, requests that need Kratos's answer, and the server's exit. Every message is
//! routed by its method name into the types `build.rs` generates from the committed schema, so a
//! field Codex renames fails to parse instead of reading as missing.

mod connection;
mod locate;
mod protocol;

/// The protocol types, generated from `schema/codex_app_server_protocol.schemas.json`.
#[allow(
    clippy::all,
    clippy::pedantic,
    reason = "generated by typify; the schema, not this crate, decides their shape"
)]
pub mod types {
    include!(concat!(env!("OUT_DIR"), "/codex_types.rs"));
}

pub use connection::{
    Codex, ConnectError, Exit, Incoming, IncomingRequest, Launch, RequestError, RequestId, connect,
};
pub use locate::{LocateError, locate_codex};
pub use protocol::{Method, Notification, ServerRequest, methods};

/// JSON-RPC's error for a method the receiver does not handle.
pub const METHOD_NOT_FOUND: i64 = -32601;
/// JSON-RPC's error for parameters the receiver cannot read.
pub const INVALID_PARAMS: i64 = -32602;
/// JSON-RPC's error for a handler that failed.
pub const INTERNAL_ERROR: i64 = -32603;

/// The codes Codex answers when it refused a request before acting on it: the request did not
/// parse, was not a valid request, named no method, or had parameters it could not read. A start
/// that fails with one of these never began a turn, so it is safe to try once more.
pub fn rejected_before_execution(code: i64) -> bool {
    matches!(code, -32700 | -32600 | -32601 | -32602)
}
